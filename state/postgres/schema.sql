-- PostgreSQL 目标数据契约：当前业务表 + 持久化任务队列
-- id 使用 BY DEFAULT IDENTITY，便于迁移时保留 SQLite 原 id；金额未知为 NULL。

CREATE TABLE IF NOT EXISTS schema_migration (
    version TEXT PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS feed (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    feed_url TEXT NOT NULL UNIQUE,
    show_name TEXT,
    etag TEXT,
    last_modified TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    bootstrap_pending BOOLEAN NOT NULL DEFAULT TRUE,
    last_checked_at TIMESTAMPTZ,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_feed_enabled ON feed(enabled);

CREATE TABLE IF NOT EXISTS episode (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guid TEXT NOT NULL,
    feed TEXT NOT NULL,
    feed_snapshot JSONB,
    title TEXT,
    published_at TIMESTAMPTZ,
    duration_secs DOUBLE PRECISION,
    enclosure TEXT,
    audio_sha256 TEXT,
    status TEXT NOT NULL DEFAULT 'discovered'
        CHECK (status IN ('discovered','downloaded','transcribed','translated','reviewing','rejected','approved','delivered','failed','parked')),
    crash_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (guid, feed)
);

CREATE TABLE IF NOT EXISTS artifact (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id BIGINT NOT NULL REFERENCES episode(id) ON DELETE CASCADE,
    step TEXT NOT NULL,
    kind TEXT NOT NULL,
    path TEXT NOT NULL,
    version INTEGER NOT NULL DEFAULT 1,
    sha256 TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','done','failed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_artifact_episode ON artifact(episode_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_artifact_identity ON artifact(episode_id, step, path, version);

CREATE TABLE IF NOT EXISTS discovery_candidate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id BIGINT NOT NULL REFERENCES feed(id),
    guid TEXT NOT NULL,
    title TEXT,
    published_at TIMESTAMPTZ,
    enclosure TEXT,
    summary TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','enqueued','skipped','failed')),
    reason TEXT,
    classification_relevant BOOLEAN,
    classification_call_ref TEXT,
    episode_id BIGINT REFERENCES episode(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (feed_id, guid)
);
CREATE INDEX IF NOT EXISTS idx_discovery_candidate_status ON discovery_candidate(status);
CREATE INDEX IF NOT EXISTS idx_discovery_candidate_episode ON discovery_candidate(episode_id);

CREATE TABLE IF NOT EXISTS ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id BIGINT REFERENCES episode(id),
    purpose TEXT NOT NULL,
    triggered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    provider TEXT,
    model TEXT,
    usage_basis TEXT,
    amount_est NUMERIC,
    call_ref TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'intent' CHECK (status IN ('intent','success','failed','unknown'))
);

CREATE TABLE IF NOT EXISTS review_revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id BIGINT NOT NULL REFERENCES episode(id) ON DELETE CASCADE,
    base_artifact_id BIGINT NOT NULL REFERENCES artifact(id),
    rendered_artifact_id BIGINT NOT NULL REFERENCES artifact(id),
    variant TEXT NOT NULL CHECK (variant IN ('review','split')),
    status TEXT NOT NULL CHECK (status IN ('reviewing','rejected','approved','delivered','superseded')),
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    reviewing_since TIMESTAMPTZ NOT NULL,
    auto_approve_at TIMESTAMPTZ,
    auto_approve_paused BOOLEAN NOT NULL DEFAULT FALSE,
    supersedes_revision_id BIGINT REFERENCES review_revision(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (is_current = FALSE OR status <> 'superseded')
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_review_revision_current ON review_revision(episode_id) WHERE is_current;
CREATE INDEX IF NOT EXISTS idx_review_revision_due ON review_revision(status, auto_approve_paused, auto_approve_at);

CREATE TABLE IF NOT EXISTS execution_lock (
    episode_id BIGINT PRIMARY KEY REFERENCES episode(id) ON DELETE CASCADE,
    owner TEXT NOT NULL,
    acquired_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_execution_lock_expiry ON execution_lock(expires_at);

CREATE TABLE IF NOT EXISTS override (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id BIGINT NOT NULL REFERENCES episode(id) ON DELETE CASCADE,
    base_revision_id BIGINT NOT NULL REFERENCES review_revision(id),
    base_artifact_id BIGINT NOT NULL REFERENCES artifact(id),
    source_artifact_id BIGINT NOT NULL REFERENCES artifact(id),
    start_ms BIGINT NOT NULL CHECK (start_ms >= 0),
    end_ms BIGINT NOT NULL CHECK (end_ms > start_ms),
    source_text_sha256 TEXT NOT NULL,
    before_text TEXT NOT NULL,
    after_text TEXT NOT NULL,
    supersedes_override_id BIGINT REFERENCES override(id),
    retracted BOOLEAN NOT NULL DEFAULT FALSE,
    request_id TEXT NOT NULL UNIQUE,
    result_revision_id BIGINT REFERENCES review_revision(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_override_episode_anchor ON override(episode_id, source_artifact_id, start_ms, end_ms);
CREATE UNIQUE INDEX IF NOT EXISTS idx_override_single_successor ON override(supersedes_override_id) WHERE supersedes_override_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS override_application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    override_id BIGINT NOT NULL REFERENCES override(id) ON DELETE CASCADE,
    candidate_artifact_id BIGINT NOT NULL REFERENCES artifact(id) ON DELETE CASCADE,
    status TEXT NOT NULL CHECK (status IN ('applied','conflict')),
    target_start_ms BIGINT,
    target_end_ms BIGINT,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (override_id, candidate_artifact_id)
);
CREATE INDEX IF NOT EXISTS idx_override_application_conflict ON override_application(candidate_artifact_id, status);

CREATE TABLE IF NOT EXISTS approval (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_revision_id BIGINT NOT NULL UNIQUE REFERENCES review_revision(id),
    episode_id BIGINT NOT NULL REFERENCES episode(id) ON DELETE CASCADE,
    artifact_id BIGINT NOT NULL REFERENCES artifact(id),
    sha256 TEXT NOT NULL,
    method TEXT NOT NULL CHECK (method IN ('manual','auto_timeout')),
    request_id TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS rerun_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id BIGINT NOT NULL REFERENCES episode(id) ON DELETE CASCADE,
    base_revision_id BIGINT NOT NULL REFERENCES review_revision(id),
    reason TEXT NOT NULL,
    ranges_json JSONB NOT NULL,
    override_ids_json JSONB NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('pending','running','completed','failed','unknown')),
    result_revision_id BIGINT REFERENCES review_revision(id),
    request_id TEXT NOT NULL UNIQUE,
    error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS delivery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_id BIGINT NOT NULL UNIQUE REFERENCES approval(id),
    episode_id BIGINT NOT NULL REFERENCES episode(id) ON DELETE CASCADE,
    artifact_id BIGINT NOT NULL REFERENCES artifact(id),
    status TEXT NOT NULL CHECK (status IN ('pending','waiting_highlights','uploading','delivered','failed','superseded')),
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    audio_key TEXT,
    subtitle_key TEXT,
    highlights_key TEXT,
    highlights_json JSONB,
    sha256 TEXT NOT NULL,
    error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (is_current = FALSE OR status = 'delivered')
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_delivery_current ON delivery(episode_id) WHERE is_current;
CREATE INDEX IF NOT EXISTS idx_delivery_pending ON delivery(status, updated_at);

-- 多用户账号、会话、资源授权、审计与预算；密码/会话仅保存哈希
CREATE TABLE IF NOT EXISTS user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('owner','admin','reviewer','viewer')),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','disabled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_account(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_session_user ON session(user_id, expires_at);

CREATE TABLE IF NOT EXISTS resource_grant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_account(id) ON DELETE CASCADE,
    resource_type TEXT NOT NULL,
    resource_id BIGINT NOT NULL,
    permission TEXT NOT NULL CHECK (permission IN ('read','review','approve','publish','admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, resource_type, resource_id, permission)
);
CREATE INDEX IF NOT EXISTS idx_resource_grant_lookup ON resource_grant(user_id, resource_type, resource_id, permission);

CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES user_account(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    resource_type TEXT NOT NULL,
    resource_id BIGINT NOT NULL,
    version TEXT,
    result TEXT NOT NULL CHECK (result IN ('success','failed','rejected')),
    details JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_audit_log_resource ON audit_log(resource_type, resource_id, created_at DESC);

CREATE TABLE IF NOT EXISTS budget_limit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope TEXT NOT NULL CHECK (scope IN ('global','user','episode')),
    user_id BIGINT REFERENCES user_account(id) ON DELETE CASCADE,
    episode_id BIGINT REFERENCES episode(id) ON DELETE CASCADE,
    period TEXT NOT NULL CHECK (period IN ('task','day','month')),
    max_amount NUMERIC,
    max_running INTEGER,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        (scope = 'global' AND user_id IS NULL AND episode_id IS NULL)
        OR (scope = 'user' AND user_id IS NOT NULL AND episode_id IS NULL)
        OR (scope = 'episode' AND episode_id IS NOT NULL)
    )
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_budget_limit_identity ON budget_limit(scope, COALESCE(user_id, 0), COALESCE(episode_id, 0), period);
CREATE INDEX IF NOT EXISTS idx_budget_limit_lookup ON budget_limit(scope, user_id, episode_id, period, enabled);

-- 持久化任务队列：付费调用幂等与业务版本由 idempotency_key / payload 绑定
CREATE TABLE IF NOT EXISTS job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id BIGINT REFERENCES episode(id) ON DELETE CASCADE,
    user_id BIGINT, -- 多用户表接入后补外键；当前用于配额归属
    kind TEXT NOT NULL CHECK (kind IN ('episode','download','transcribe','translate','review','highlights','publish','rerun')),
    status TEXT NOT NULL DEFAULT 'ready' CHECK (status IN ('ready','running','retry','failed','parked','completed')),
    payload JSONB NOT NULL,
    idempotency_key TEXT NOT NULL UNIQUE,
    priority INTEGER NOT NULL DEFAULT 0,
    available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    locked_by TEXT,
    locked_until TIMESTAMPTZ,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    max_attempts INTEGER NOT NULL DEFAULT 3 CHECK (max_attempts > 0),
    budget NUMERIC,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (status <> 'running' OR (locked_by IS NOT NULL AND locked_until IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_job_claim ON job(status, available_at, priority DESC, id);
CREATE INDEX IF NOT EXISTS idx_job_lease ON job(status, locked_until);
CREATE INDEX IF NOT EXISTS idx_job_episode ON job(episode_id);
CREATE INDEX IF NOT EXISTS idx_job_user ON job(user_id, status);

CREATE TABLE IF NOT EXISTS job_attempt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES job(id) ON DELETE CASCADE,
    attempt_no INTEGER NOT NULL,
    worker_id TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'running' CHECK (status IN ('running','succeeded','failed','unknown')),
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    result JSONB,
    usage JSONB,
    error TEXT,
    UNIQUE (job_id, attempt_no)
);
CREATE INDEX IF NOT EXISTS idx_job_attempt_job ON job_attempt(job_id, attempt_no DESC);
